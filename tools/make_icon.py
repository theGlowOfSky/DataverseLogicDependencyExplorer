"""Generates the plugin icon (dependency-graph motif): assets/icon-256.png, assets/icon.ico and Resources/IconData.cs."""
import base64, io, os
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BLUE, LIGHT = (15, 108, 189, 255), (255, 255, 255, 255)

def draw(size):
    s = size * 4  # supersample
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, s - 1, s - 1], radius=int(s * 0.2), fill=BLUE)
    c = (s * 0.30, s * 0.5)                       # source node
    t = [(s * 0.72, s * 0.24), (s * 0.76, s * 0.5), (s * 0.72, s * 0.76)]  # dependents
    w = max(2, int(s * 0.035))
    for p in t:
        d.line([c, p], fill=LIGHT, width=w)
    r0, r1 = s * 0.115, s * 0.075
    d.ellipse([c[0] - r0, c[1] - r0, c[0] + r0, c[1] + r0], fill=LIGHT)
    for p in t:
        d.ellipse([p[0] - r1, p[1] - r1, p[0] + r1, p[1] + r1], fill=LIGHT)
    d.ellipse([c[0] - r0 * .45, c[1] - r0 * .45, c[0] + r0 * .45, c[1] + r0 * .45], fill=BLUE)
    return img.resize((size, size), Image.LANCZOS)

def b64(img):
    buf = io.BytesIO(); img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()

os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
draw(256).save(os.path.join(ROOT, "assets", "icon-256.png"))
draw(256).save(os.path.join(ROOT, "assets", "icon.ico"), sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
src = os.path.join(ROOT, "src", "DataverseLogicDependencyExplorer", "Resources", "IconData.cs")
with open(src, "w") as f:
    f.write("// ----------------------------------------------------------------------------\n// Dataverse Logic Dependency Explorer  v1.2026.11.11\n// Maintainer: Gagan Deep Singh  |  LinkedIn: https://www.linkedin.com/in/glowofsky/\n// Host: XrmToolBox  |  Data platform: Microsoft Dataverse  |  Export format: Excel workbook (.xlsx)\n// ----------------------------------------------------------------------------\n")
    f.write("namespace DataverseLogicDependencyExplorer.Resources\n{\n    /// <summary>Base64 PNG icons used in the XrmToolBox plugin metadata (generated by tools/make_icon.py).</summary>\n    internal static class IconData\n    {\n")
    f.write('        public const string Small32 = "%s";\n\n' % b64(draw(32)))
    f.write('        public const string Big80 = "%s";\n' % b64(draw(80)))
    f.write("    }\n}\n")
print("icon generated")
